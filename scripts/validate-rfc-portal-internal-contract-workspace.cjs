'use strict';
const assert=require('node:assert/strict'),fs=require('fs'),path=require('path');
const read=rel=>fs.readFileSync(path.join(process.cwd(),rel),'utf8');
const dashboard=read('dashboard.html');
const matches=read('netlify/functions/ngcc-federal-matches.mjs');
const detail=read('netlify/functions/ngcc-federal-contract.mjs');
const pkg=read('netlify/functions/ngcc-federal-contract-package.mjs');
const page=read('federal-contract.html');
assert.match(dashboard,/\/federal-contract\.html\?id=/,'federal match selection must open the internal contract workspace');
assert.doesNotMatch(dashboard,/View Official Listing/i,'customer dashboard must not expose an upstream official-listing link');
assert.doesNotMatch(dashboard,/sam\.gov/i,'customer dashboard must not expose SAM.gov');
assert.doesNotMatch(matches,/ui_link\s*:/,'federal match payload must not return ui_link');
assert.doesNotMatch(matches,/https:\/\/sam\.gov/i,'federal match API must not emit SAM.gov URLs');
assert.match(detail,/loadProfileSession/,'internal contract detail must require the verified customer session');
assert.match(detail,/\/api\/federal-contract-package\?id=/,'internal contract detail must hand off package downloads to Apropos');
assert.doesNotMatch(detail,/sam\.gov/i,'customer contract detail payload must not expose SAM.gov');
assert.match(pkg,/loadProfileSession/,'package download must require the verified customer session');
assert.doesNotMatch(pkg,/official_sam_url|source_url\s*:/i,'customer package manifest must not expose upstream URLs');
assert.doesNotMatch(pkg,/Use the official SAM\.gov|direct SAM\.gov access/i,'package errors must not redirect customers upstream');
assert.match(page,/Federal Contract Workspace/,'internal customer contract workspace page must exist');
assert.match(page,/Download Contract Package/,'workspace must provide an Apropos package action');
assert.match(page,/Analyze Fit — \$79/,'workspace must retain optional Analyze Fit');
assert.doesNotMatch(page,/sam\.gov/i,'customer contract workspace must not mention or link SAM.gov');
console.log('RFC Portal internal contract workspace validation passed.');